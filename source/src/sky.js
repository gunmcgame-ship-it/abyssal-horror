// Star instances for the sky pipeline: direction (xyz) + peak brightness, colour (rgb) + twinkle seed.
// One extra slot at the end is the satellite, rewritten every frame (satellite() below).
function starData() {
  const d = new Float32Array((STARS.length + 1) * 8);
  STARS.forEach(([ra, de, mg, bv], i) => {
    const v = raDec(ra, de), t = clamp((bv + 0.3) / 2.1, 0, 1);
    // colour from B-V: blue-white through white and yellow to orange
    const c = [mix(0.72, 1.0, sstep(0, 0.45, t)), mix(0.82, 0.74, t * t) + 0.12 * (1 - abs(t - 0.35) * 2), mix(1.2, 0.42, sstep(0.1, 1, t))];
    d.set([v[0], v[1], v[2], 5 * pow(10, -0.4 * mg), c[0], c[1], c[2], i * 0.618], i * 8);
  });
  return d;
}

// ---------------------------------------------------------------- satellites
// In the hour before dawn, satellites high up are still in sunlight while the ground is dark. In November 1957 the
// bright ones were Sputnik 1's spent rocket stage (tumbling, so it pulsed between about magnitude 1 and 3) and
// Sputnik 2 (launched 3 November, still joined to its own rocket stage, about magnitude 1.5, steadier).
// Each pass: start (seconds of play), heading of the ground track (degrees from north), how far the track passes from
// overhead (degrees across the earth), height (km), magnitude at 1000 km, tumbling period (s, 0 steady).
// The play is compressed, the sky is not: a pass takes its real ten-odd minutes horizon to horizon.
const SATS = [[170, 135, 4, 640, 1.2, 7.5], [980, 40, -9, 760, 1.6, 0], [1830, 150, -13, 600, 1.2, 7.5], [2700, 45, 6, 780, 1.6, 0]];
const SUN = altAz(-15.1, 99); // the sun at 5:05 a.m., below the eastern horizon
const RE = 6371;
// position of pass s at time t: world direction (xyz) and brightness; brightness 0 when it is below the horizon or in
// the earth's shadow
function satAt(s, t, o) {
  const [t0, hd, off, h, m0, tum] = s, dt = t - t0, w = 7.6 / (RE + h); // angular speed round the earth (rad/s)
  const th = (dt - 420) * w, ho = hd * PI / 180, of = off * PI / 180, r = RE + h;
  // the orbit's great circle: its closest point to overhead is u, it moves along the heading v
  const u = [sin(of) * -sin(ho), cos(of), sin(of) * cos(ho)], v = [cos(ho), 0, sin(ho)];
  const p = [r * (u[0] * cos(th) + v[0] * sin(th)), r * (u[1] * cos(th) + v[1] * sin(th)) - RE, r * (u[2] * cos(th) + v[2] * sin(th))]; // from the observer
  const d = hypot(...p); o[0] = p[0] / d; o[1] = p[1] / d; o[2] = p[2] / d;
  if (dt < 0 || o[1] < 0.02) return 0;
  // earth's shadow: a cylinder behind the earth, away from the sun (centre at (0, -RE, 0))
  const q = [p[0], p[1] + RE, p[2]], al = q[0] * SUN[0] + q[1] * SUN[1] + q[2] * SUN[2];
  const ax = hypot(q[0] - SUN[0] * al, q[1] - SUN[1] * al, q[2] - SUN[2] * al);
  const lit = al > 0 ? 1 : sstep(RE - 30, RE + 30, ax);
  const mg = m0 + 5 * Math.log10(d / 1000) + 1.2 / max(o[1], 0.05) * 0.18; // farther and lower down: fainter
  const fl = tum ? 0.25 + 0.75 * pow(abs(sin(dt * PI / tum)), 3) : 1;
  return lit * fl * 5 * pow(10, -0.4 * mg) * sstep(0.02, 0.08, o[1]);
}
const satO = [0, 0, 0];
// the satellite slot of the star buffer at play time t (seconds)
function satellite(t, out) {
  out[3] = 0;
  for (const s of SATS) { const b = satAt(s, t, satO); if (b > 0 || (t > s[0] && t < s[0] + 900)) { out[0] = satO[0]; out[1] = satO[1]; out[2] = satO[2]; out[3] = b; if (b > 0) break; } }
  out[4] = 1; out[5] = 0.97; out[6] = 0.9; out[7] = 0;
}
