// The sky is frozen at 5:05 a.m. Pacific time on 7 November 1957 (when totality begins, see main.js) as seen from the
// fictional canyon at 35.5 N, 117.5 W. Compass in world space: +x north, +z east, -z west, +y up.
const SKY_LAT = 35.5, SKY_LON = -117.5, SKY_JD = 2436149.5 + (5 + 5 / 60 + 8) / 24;
const SKY_LST = ((280.46061837 + 360.98564736629 * (SKY_JD - 2451545) + SKY_LON) % 360 + 360) % 360;
// world direction of a point at (altitude, azimuth) in degrees
const altAz = (al, az) => { const a = al * PI / 180, z = az * PI / 180; return [cos(a) * cos(z), sin(a), cos(a) * sin(z)]; };
// world direction of right ascension (hours) and declination (degrees) at that moment
const raDec = (ra, de) => {
  const R = PI / 180, H = (SKY_LST - ra * 15) * R, d = de * R, la = SKY_LAT * R;
  const al = Math.asin(sin(la) * sin(d) + cos(la) * cos(d) * cos(H));
  const az = Math.atan2(sin(H), cos(H) * sin(la) - Math.tan(d) * cos(la)) + PI;
  return altAz(al / R, az / R);
};

